"""Bundle the Telegram bot into one file for the Supabase dashboard editor.

    python scripts/build_bot.py          # writes backend/functions/telegram-bot/index.ts
    python scripts/build_bot.py --check  # exit 1 if index.ts is out of date (used by tests)

The bot reuses the app's tested modules. Each module is wrapped in its own scope (so names can't
clash) and its imports become reads from the other modules' scopes. No npm, no bundler.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FN = ROOT / "backend" / "functions" / "telegram-bot"
MODULES = [
    "web/lib/risk-defaults.js",
    "web/lib/portfolio.js",
    "web/lib/sizing.js",
    "web/lib/thesis.js",
    "backend/functions/telegram-bot/core.js",
]
ENTRY = "backend/functions/telegram-bot/server.js"
OUT = FN / "index.ts"

IMPORT = re.compile(r'^import\s*\{([^}]*)\}\s*from\s*"([^"]+)";[ \t]*$', re.M)
EXPORT_DECL = re.compile(
    r"^export\s+(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)", re.M
)
EXPORT_LIST = re.compile(r"^export\s*\{([^}]*)\};?[ \t]*$", re.M)


def ns(rel: str) -> str:
    return "__" + re.sub(r"\W", "_", Path(rel).stem)


def transform(rel: str, wrap: bool) -> str:
    src = (ROOT / rel).read_text()
    base = (ROOT / rel).parent

    def imp(m: re.Match) -> str:
        target = (base / m.group(2)).resolve().relative_to(ROOT).as_posix()
        if target not in MODULES:
            raise SystemExit(f"{rel}: can't bundle import of {target}")
        names = ", ".join(
            f"{a.strip()}: {b.strip()}" if " as " in x else x.strip()
            for x in m.group(1).split(",")
            if x.strip()
            for a, _, b in [x.partition(" as ")]
        )
        return f"const {{ {names} }} = {ns(target)};"

    body = IMPORT.sub(imp, src)
    names = EXPORT_DECL.findall(body)
    for m in EXPORT_LIST.finditer(body):
        names += [x.strip() for x in m.group(1).split(",") if x.strip()]
    body = EXPORT_LIST.sub("", body)
    body = re.sub(r"^export\s+", "", body, flags=re.M)
    if not wrap:
        return body
    exports = ", ".join(names)
    return f"// ---- {rel}\nconst {ns(rel)} = (() => {{\n{body}\nreturn {{ {exports} }};\n}})();\n"


def build() -> str:
    head = (
        "// @ts-nocheck — GENERATED by scripts/build_bot.py, do not edit by hand.\n"
        '// Supabase Edge Function "telegram-bot" (CLAUDE.md 13.16 B): read-only Telegram\n'
        "// commands for the owner's chat only.\n"
        "// Sources: backend/functions/telegram-bot/{core,server}.js + web/lib/*.\n"
        "// Deploy: dashboard → Edge Functions → telegram-bot → paste this file; Verify JWT OFF;\n"
        "// secrets TELEGRAM_BOT_TOKEN and TELEGRAM_CHAT_ID.\n\n"
    )
    modules = "\n".join(transform(m, True) for m in MODULES)
    return head + modules + "\n// ---- " + ENTRY + "\n" + transform(ENTRY, False)


if __name__ == "__main__":
    out = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == out else 1)
    OUT.write_text(out)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(out)} chars)")
